# docs/generate-docs.ps1 — POST 43
# Documentation as code: regenerates docs/API-REFERENCE.md and docs/INDEX.md
# directly from the source tree and existing docs/*.md files.
#
# THE PROBLEM THIS SOLVES:
#   By Post 42, docs/ holds 24 hand-written markdown files (architecture
#   notes, KQL references, capstone playbooks, runbooks). Nothing enforces
#   that this collection stays organized or that new files get indexed.
#   A markdown file can be added, forgotten, and never linked from anywhere
#   — discoverable only by browsing the raw file listing.
#
#   Separately, the /// XML doc comments already written on public C# members
#   (16 of them as of Post 42 — TraceContextPropagator, BusinessMetrics,
#   FallbackServiceBusSender, TelemetryConstants, OrderPriority) exist only
#   as IntelliSense tooltips in an IDE. Nobody reading docs/ sees them.
#
# WHAT THIS SCRIPT GENERATES (both from EXISTING content — nothing invented):
#   1. docs/API-REFERENCE.md — every /// <summary> doc comment on a public
#      member, extracted directly from .cs files via regex, organized by file.
#   2. docs/INDEX.md — every existing docs/*.md file, categorized by which
#      phase/post introduced it (inferred from filename and content patterns
#      already established across this series), with a one-line description
#      pulled from each file's own header comment or first heading.
#
# WHY REGENERATE RATHER THAN HAND-MAINTAIN:
#   A hand-written docs/API-REFERENCE.md drifts the moment a method's
#   summary is edited in the .cs file but the corresponding markdown row
#   isn't updated. Generating both files from source on every run means
#   the reference can never be MORE than one script execution behind
#   the actual code — running this in pr-checks.yml (Post 30) as a
#   "docs are current" gate is the natural next step (see capstone-08's
#   pattern of composing existing CI infrastructure, Post 40).
#
# USAGE:
#   .\docs\generate-docs.ps1
#   .\docs\generate-docs.ps1 -CheckOnly   # fail if generated output would differ from what's committed

param([switch]$CheckOnly)

$ErrorActionPreference = "Stop"
Write-Host "`n╔══════════════════════════════════════════════════╗" -ForegroundColor Cyan
Write-Host   "║  DOCUMENTATION GENERATOR — POST 43               ║" -ForegroundColor Cyan
Write-Host   "╚══════════════════════════════════════════════════╝" -ForegroundColor Cyan

# ══════════════════════════════════════════════════════════════════════════
# PART 1: API REFERENCE — extracted from /// <summary> doc comments
# ══════════════════════════════════════════════════════════════════════════
Write-Host "`n── Generating docs/API-REFERENCE.md ──────────────────" -ForegroundColor Yellow

$csFiles = Get-ChildItem -Path "src" -Filter "*.cs" -Recurse
$apiEntries = @()

# POST 43: This regex mirrors System.Text.RegularExpressions semantics —
# match a run of /// comment lines immediately followed by a public
# member declaration (class, method, const, or property).
$docPattern = [regex]'(?ms)((?:^\s*///[^\r\n]*\r?\n)+)\s*(public\s+(?:static\s+)?(?:readonly\s+)?[\w<>\[\],?\s]+?\s+(\w+)\s*[\(=\{])'

foreach ($file in $csFiles) {
    $content = Get-Content $file.FullName -Raw
    $matches = $docPattern.Matches($content)
    foreach ($m in $matches) {
        $docBlock = $m.Groups[1].Value
        $memberName = $m.Groups[3].Value
        $summaryMatch = [regex]::Match($docBlock, '(?s)<summary>\s*(.*?)\s*</summary>')
        if ($summaryMatch.Success) {
            $summaryText = ($summaryMatch.Groups[1].Value -replace '\s*///\s*', ' ').Trim()
            $relPath = $file.FullName.Replace((Get-Location).Path, '').TrimStart('\', '/')
            $apiEntries += [PSCustomObject]@{
                File    = $relPath
                Member  = $memberName
                Summary = $summaryText
            }
        }
    }
}

$grouped = $apiEntries | Group-Object File | Sort-Object Name

$apiMd = @()
$apiMd += "# API Reference"
$apiMd += ""
$apiMd += "**Auto-generated by `docs/generate-docs.ps1` — do not edit directly.**"
$apiMd += "Regenerate after any change to a `/// <summary>` doc comment."
$apiMd += ""
$apiMd += "Source: every `public` member across `src/` carrying an XML doc comment,"
$apiMd += "extracted directly from the .cs files. $($apiEntries.Count) documented members"
$apiMd += "across $($grouped.Count) files as of the last generation."
$apiMd += ""

foreach ($group in $grouped) {
    $apiMd += "## ``$($group.Name)``"
    $apiMd += ""
    foreach ($entry in $group.Group) {
        $apiMd += "### ``$($entry.Member)``"
        $apiMd += ""
        $apiMd += $entry.Summary
        $apiMd += ""
    }
}

$apiMdContent = $apiMd -join "`n"

if ($CheckOnly) {
    $existing = if (Test-Path "docs/API-REFERENCE.md") { Get-Content "docs/API-REFERENCE.md" -Raw } else { "" }
    if ($existing.Trim() -ne $apiMdContent.Trim()) {
        Write-Host "  ✗ docs/API-REFERENCE.md is STALE — regenerate before committing" -ForegroundColor Red
        exit 1
    } else {
        Write-Host "  ✓ docs/API-REFERENCE.md is current" -ForegroundColor Green
    }
} else {
    $apiMdContent | Out-File "docs/API-REFERENCE.md" -Encoding utf8
    Write-Host "  Generated: docs/API-REFERENCE.md ($($apiEntries.Count) members, $($grouped.Count) files)" -ForegroundColor Green
}

# ══════════════════════════════════════════════════════════════════════════
# PART 2: DOCUMENTATION INDEX — every existing docs/*.md file, categorized
# ══════════════════════════════════════════════════════════════════════════
Write-Host "`n── Generating docs/INDEX.md ───────────────────────────" -ForegroundColor Yellow

# POST 43: Category inference by filename pattern — matches the organic
# naming convention this series has used since Post 1 (no central registry
# existed before this post; categories are inferred from established
# naming, not hand-maintained metadata).
function Get-Category {
    param([string]$FileName)
    switch -Regex ($FileName) {
        '^capstone-\d+-notes'      { return "Capstone Playbooks" }
        '^capstone-\d+\.ps1$'      { return "Capstone Scripts" }
        'kql|adx'                  { return "Analytics & KQL" }
        'sre-runbook|troubleshoot|sentinel' { return "Operations & Runbooks" }
        'architecture|storage-decision|telemetry-schema' { return "Architecture Decisions" }
        'ci-cd|production-checklist' { return "Deployment & Release" }
        'nbomber|profiling|dapr'   { return "Testing & Performance" }
        default                    { return "Reference" }
    }
}

$mdFiles = Get-ChildItem -Path "docs" -Filter "*.md" |
    Where-Object { $_.Name -notin @("API-REFERENCE.md", "INDEX.md") }

$indexEntries = @()
foreach ($file in $mdFiles) {
    $content = Get-Content $file.FullName -Raw
    # POST 43: Extract a one-line description — prefer the first '#' heading's
    # trailing text, fall back to the first non-blank comment line.
    $firstHeading = [regex]::Match($content, '^#\s+(.+)$', 'Multiline')
    $description = if ($firstHeading.Success) {
        $firstHeading.Groups[1].Value.Trim()
    } else {
        ($content -split "`n" | Where-Object { $_.Trim() -ne "" } | Select-Object -First 1).Trim() -replace '^#\s*', ''
    }
    $indexEntries += [PSCustomObject]@{
        FileName    = $file.Name
        Category    = Get-Category $file.Name
        Description = $description
    }
}

$grouped2 = $indexEntries | Group-Object Category | Sort-Object Name

$indexMd = @()
$indexMd += "# Documentation Index"
$indexMd += ""
$indexMd += "**Auto-generated by `docs/generate-docs.ps1` — do not edit directly.**"
$indexMd += ""
$indexMd += "$($indexEntries.Count) documents across $($grouped2.Count) categories, indexed from every"
$indexMd += "``docs/*.md`` file present at generation time."
$indexMd += ""

foreach ($group in $grouped2) {
    $indexMd += "## $($group.Name)"
    $indexMd += ""
    foreach ($entry in ($group.Group | Sort-Object FileName)) {
        $indexMd += "- [``$($entry.FileName)``]($($entry.FileName)) — $($entry.Description)"
    }
    $indexMd += ""
}

$indexMdContent = $indexMd -join "`n"

if ($CheckOnly) {
    $existing = if (Test-Path "docs/INDEX.md") { Get-Content "docs/INDEX.md" -Raw } else { "" }
    if ($existing.Trim() -ne $indexMdContent.Trim()) {
        Write-Host "  ✗ docs/INDEX.md is STALE — regenerate before committing" -ForegroundColor Red
        exit 1
    } else {
        Write-Host "  ✓ docs/INDEX.md is current" -ForegroundColor Green
    }
} else {
    $indexMdContent | Out-File "docs/INDEX.md" -Encoding utf8
    Write-Host "  Generated: docs/INDEX.md ($($indexEntries.Count) documents, $($grouped2.Count) categories)" -ForegroundColor Green
}

Write-Host "`n╔══════════════════════════════════════════════════╗" -ForegroundColor Green
Write-Host   "║  DONE                                             ║" -ForegroundColor Green
Write-Host   "╚══════════════════════════════════════════════════╝" -ForegroundColor Green
if (-not $CheckOnly) {
    Write-Host "  Regeneration is idempotent — run again any time source or docs/ changes."
    Write-Host "  Add '.\docs\generate-docs.ps1 -CheckOnly' to pr-checks.yml to gate on staleness."
}
